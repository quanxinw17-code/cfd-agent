def _markdown_report(report: dict[str, Any]) -> str:
    lines = ["# CFD Agent Deployment Check", "", f"Overall: {'OK' if report['ok'] else 'Needs attention'}", ""]
    for name, check in report["checks"].items():
        lines.append(f"- {name}: {'OK' if check.get('ok') else 'Missing'}")
        if check.get("path"):
            lines.append(f"  Path: `{check['path']}`")
        if check.get("message"):
            lines.append(f"  Note: {check['message']}")
    return "\n".join(lines) + "\n"


def _smoke_markdown_report(report: dict[str, Any]) -> str:
    lines = ["# CFD Agent Software Smoke Check", "", f"Overall: {'OK' if report['ok'] else 'Needs attention'}", ""]
    for name, check in report["checks"].items():
        lines.append(f"- {name}: {'OK' if check.get('ok') else 'Failed'}")
        lines.append(f"  Note: {check.get('message', '')}")
        if check.get("log_file"):
            lines.append(f"  Log: `{check['log_file']}`")
    return "\n".join(lines) + "\n"
